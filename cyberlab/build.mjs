// 依存ゼロの簡易ESMバンドラ。
// js/ 以下のモジュールを1ファイル(app.bundle.js)に結合し、起動時のHTTPリクエストを激減させる。
// 使い方: node build.mjs   (js/ を変更したら再実行してコミットする)
//
// 対応する構文: 単一行 import { ... } from './x.js' / import * as ns from './x.js'
//               export const/class/function/async function NAME / export { a, b }
// 非対応: default export, 動的 import, 複数行 import（本プロジェクトは未使用）
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const DEFAULT_ENTRY = 'js/app.js';

function resolveId(fromId, spec) {
  const dir = path.dirname(fromId);
  return path.normalize(path.join(dir, spec)).split(path.sep).join('/');
}

// js/ 以下を結合したバンドル文字列を返す（baseDir はこのスクリプトのあるディレクトリ基準）
export function bundle(baseDir = path.dirname(fileURLToPath(import.meta.url)), { entry = DEFAULT_ENTRY, expose = false } = {}) {
const files = new Map();   // id -> { src, exports }
const order = [];
const visited = new Set();
const stack = [];   // 読み込み中のモジュール（循環参照の検出用）

function load(id) {
  if (stack.includes(id)) throw new Error(`循環参照を検出: ${[...stack.slice(stack.indexOf(id)), id].join(' -> ')}（バンドルでは未初期化の export を掴んで壊れるため禁止。葉モジュールに分離してください）`);
  if (visited.has(id)) return;
  visited.add(id);
  stack.push(id);
  let src = fs.readFileSync(path.join(baseDir, id), 'utf8');
  const exports = [];

  // import * as ns from './x.js'
  src = src.replace(/^import\s+\*\s+as\s+(\w+)\s+from\s+'([^']+)';?[ \t]*$/gm, (m, ns, spec) => {
    const dep = resolveId(id, spec); load(dep);
    return `const ${ns} = __require(${JSON.stringify(dep)});`;
  });
  // import { a, b as c } from './x.js'
  src = src.replace(/^import\s+\{([^}]+)\}\s+from\s+'([^']+)';?[ \t]*$/gm, (m, names, spec) => {
    const dep = resolveId(id, spec); load(dep);
    const binds = names.split(',').map(s => s.trim()).filter(Boolean)
      .map(s => s.replace(/\s+as\s+/, ': ')).join(', ');
    return `const { ${binds} } = __require(${JSON.stringify(dep)});`;
  });
  // export const/class/function/async function NAME
  src = src.replace(/^export\s+(async\s+function|function|const|class)\s+(\w+)/gm, (m, kw, name) => {
    exports.push(name);
    return `${kw} ${name}`;
  });
  // export { a, b, c }
  src = src.replace(/^export\s+\{([^}]+)\};?[ \t]*$/gm, (m, names) => {
    names.split(',').forEach(s => { const nm = s.trim().split(/\s+as\s+/).pop().trim(); if (nm) exports.push(nm); });
    return '';
  });

  stack.pop();
  order.push(id);
  files.set(id, { src, exports });
}

load(entry);

let out = '';
out += '// AUTO-GENERATED by build.mjs — 編集しないこと。元ソースは js/ 以下。\n';
out += '(function () {\n';
out += '  "use strict";\n';
out += '  var __cache = {}, __mods = {};\n';
out += '  function __require(id) {\n';
out += '    if (__cache[id]) return __cache[id].exports;\n';
out += '    var module = { exports: {} }; __cache[id] = module;\n';
out += '    __mods[id](module, module.exports, __require);\n';
out += '    return module.exports;\n';
out += '  }\n';
for (const id of order) {
  const { src, exports } = files.get(id);
  out += `__mods[${JSON.stringify(id)}] = function (module, exports, __require) {\n`;
  out += src;
  if (exports.length) out += `\nObject.assign(exports, { ${[...new Set(exports)].join(', ')} });\n`;
  out += '\n};\n';
}
out += expose ? `return __require(${JSON.stringify(entry)});\n` : `__require(${JSON.stringify(entry)});\n`;
out += '})();\n';
  return { code: out, count: order.length };
}

// 直接実行された場合はファイルに書き出す
const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isMain) {
  const baseDir = path.dirname(fileURLToPath(import.meta.url));
  const { code, count } = bundle(baseDir);
  fs.writeFileSync(path.join(baseDir, 'app.bundle.js'), code);
  console.log(`bundled ${count} modules -> app.bundle.js (${Math.round(code.length / 1024)} KB)`);
}
